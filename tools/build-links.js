// Generates the short-link redirect pages (housetandem.com/tt, /ig, ...) from tools/links.json.
// GitHub Pages can't do server redirects, so each slug is a tiny static page that forwards with UTM tags.
//   node tools/build-links.js          write <slug>/index.html for every link
//   node tools/build-links.js --check  fail if any generated page is missing or out of date (for CI)
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
// Top-level names a slug must never overwrite.
const RESERVED = new Set(['css', 'js', 'images', 'tools', 'docs', 'workers', 'tandemonium', 'node_modules', 'test']);

function targetUrl(slug, link) {
  const qs = new URLSearchParams();
  for (const k of ['utm_source', 'utm_medium', 'utm_campaign', 'utm_content']) {
    if (link[k]) qs.set(k, link[k]);
  }
  if (!qs.has('utm_campaign')) qs.set('utm_campaign', slug);
  return `${link.to || '/'}?${qs}`;
}

function page(slug, link) {
  const to = targetUrl(slug, link);
  return `<!DOCTYPE html>
<!-- Generated by tools/build-links.js from tools/links.json. Don't edit by hand. -->
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="robots" content="noindex">
<title>House Tandem</title>
<meta http-equiv="refresh" content="0; url=${to}">
<link rel="canonical" href="https://housetandem.com/">
<script>location.replace(${JSON.stringify(to)} + location.hash);</script>
</head>
<body><a href="${to}">House Tandem</a></body>
</html>
`;
}

function build({ check = false } = {}) {
  const { links } = JSON.parse(fs.readFileSync(path.join(__dirname, 'links.json'), 'utf8'));
  const problems = [];
  for (const [slug, link] of Object.entries(links)) {
    if (!/^[a-z0-9-]+$/.test(slug) || RESERVED.has(slug)) throw new Error(`bad slug: ${slug}`);
    const file = path.join(ROOT, slug, 'index.html');
    const html = page(slug, link);
    if (check) {
      // Windows checkouts may have CRLF line endings; compare content only.
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== html) problems.push(slug);
    } else {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, html);
    }
  }
  return problems;
}

module.exports = { targetUrl, page, build };

if (require.main === module) {
  const check = process.argv.includes('--check');
  const problems = build({ check });
  if (problems.length) {
    console.error(`out of date: ${problems.join(', ')} (run node tools/build-links.js)`);
    process.exit(1);
  }
  console.log(check ? 'short links up to date' : 'short links written');
}
